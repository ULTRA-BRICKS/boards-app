function path(s) {
  const t = s.match(/[MLCZ]|-?\d+(?:\.\d+)?/g) || [],
    r = [];
  for (let i = 0; i < t.length;) {
    const op = t[i++],
      n = { M: 2, L: 2, C: 6, Z: 0 }[op];
    if (n === undefined) throw Error("Bad drawing");
    r.push([op, ...t.slice(i, i + n).map(Number)]);
    i += n;
  }
  return r;
}
