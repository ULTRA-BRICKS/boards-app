#!/usr/bin/env bash
# Trusted-main CI only. Publish an allowlisted set of public fixture screenshots.
set -euo pipefail
: "${EVIDENCE_DIR:?Missing downloaded browser artifact}"
: "${GITHUB_SHA:?Missing source commit}"
: "${GITHUB_RUN_ID:?Missing run ID}"
: "${GITHUB_REPOSITORY:?Missing repository}"
: "${GITHUB_SERVER_URL:?Missing GitHub server URL}"
[[ ${GITHUB_EVENT_NAME:-} == push && ${GITHUB_REF:-} == refs/heads/main ]] || {
  echo 'Evidence publication only runs for a trusted main push.' >&2; exit 1;
}
[[ $GITHUB_SHA =~ ^[0-9a-f]{40}$ ]] || exit 1
[[ $GITHUB_RUN_ID =~ ^[0-9]+$ ]] || exit 1
for name in board-desktop.png board-mobile-viewport.png type-site.png; do
  path="$EVIDENCE_DIR/docs/screenshots/$name"
  [[ -f "$path" && ! -L "$path" ]] || { echo "Missing screenshot $name" >&2; exit 1; }
done
# Keep artifacts outside the checkout before switching its branch.
source_dir=$(mktemp -d)
trap 'rm -rf "$source_dir"' EXIT
for name in board-desktop.png board-mobile-viewport.png type-site.png; do
  cp "$EVIDENCE_DIR/docs/screenshots/$name" "$source_dir/$name"
done
cp "$EVIDENCE_DIR/docs/browser-verification.json" "$source_dir/browser-verification.json"

if git ls-remote --exit-code --heads origin visual-evidence >/dev/null; then
  git fetch --depth=1 origin refs/heads/visual-evidence
  git checkout -B visual-evidence FETCH_HEAD
else
  status=$?
  [[ $status == 2 ]] || exit "$status"
  git checkout --orphan visual-evidence
  git rm -rf --ignore-unmatch .
fi
mkdir -p screenshots
cp "$source_dir"/*.png screenshots/
cp "$source_dir/browser-verification.json" .
printf '{"sourceCommit":"%s","run":"%s/%s/actions/runs/%s","mode":"native Chromium; public fixtures only"}\n' \
 "$GITHUB_SHA" "$GITHUB_SERVER_URL" "$GITHUB_REPOSITORY" "$GITHUB_RUN_ID" > evidence.json
printf '# Visual evidence\n\nGenerated by successful native Chromium CI, not by an image model.\n\nSource and run: see [evidence.json](evidence.json). Only public sample tasks and image silhouettes are used. No credentials, real profile photos, font binaries or databases are published.\n\n![Board](screenshots/board-desktop.png)\n' > README.md
git config user.name 'github-actions[bot]'
git config user.email '41898282+github-actions[bot]@users.noreply.github.com'
git add screenshots browser-verification.json evidence.json README.md
if git diff --cached --quiet; then exit 0; fi
git commit -m "docs: render visual evidence for ${GITHUB_SHA:0:12}"
# No force push: concurrent updates must be detected, not discarded.
git push origin HEAD:refs/heads/visual-evidence
